// Проверки хранилища не идут параллельно.
//
// Причина конкретная и не умозрительная: у Microsoft.Data.Sqlite пул соединений
// один на процесс, а каждая проверка в конце вызывает ClearAllPools(), чтобы
// освободить файл базы во временном каталоге. Вызов глобальный — он закрывает
// и те соединения, которыми в этот момент пользуется соседний класс проверок,
// и тот падает с ObjectDisposedException в середине создания схемы.
//
// Отказ выглядит как случайный и воспроизводится далеко не каждый запуск —
// то есть ровно так, как выглядит настоящий дефект гонки. Поймано при добавлении
// девятого класса проверок хранилища в И-17.
[assembly: CollectionBehavior(DisableTestParallelization = true)]
