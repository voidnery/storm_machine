namespace StormMachine.Protocol;

/// <summary>
/// Версия протокола и правило совместимости.
/// </summary>
/// <remarks>
/// Клиент и агент обновляются порознь. Агент живёт на чужой машине, куда никто не пойдёт
/// ради обновления, и через полгода на площадке окажется версия, о которой текущий клиент
/// ничего не знает. Значит несовместимость — не исключительная ситуация, а обычная,
/// и обращаться с ней надо соответственно.
/// <para>
/// Правило простое: старшая версия обязана совпадать, младшая у собеседника может быть
/// любой. Старшая меняется, когда меняется смысл существующих полей; младшая — когда
/// добавляются новые, которые старая сторона просто не увидит.
/// </para>
/// <para>
/// Проверка версий идёт <b>первым сообщением после TLS</b> и до всего остального. Иначе
/// несовместимость проявилась бы ошибкой разбора где-то в середине обмена, и оператор
/// увидел бы «неожиданный конец потока» вместо «агент версии 2, клиент версии 1».
/// </para>
/// </remarks>
public static class ProtocolVersion
{
    /// <summary>Старшая версия: меняется при изменении смысла существующих полей.</summary>
    public const int Major = 1;

    /// <summary>Младшая версия: меняется при добавлении полей, невидимых старой стороне.</summary>
    public const int Minor = 0;

    /// <summary>Как продукт представляется собеседнику.</summary>
    public const string Text = "storm/1.0";

    /// <summary>Совместимы ли стороны.</summary>
    public static bool IsCompatibleWith(int major) => major == Major;

    /// <summary>
    /// Почему не совместимы — текстом, который можно показать оператору.
    /// </summary>
    /// <remarks>
    /// Называется и что делать. «Версии не совпадают» отправляет человека гадать,
    /// какую из двух сторон обновлять, а обновление агента на чужой площадке —
    /// это поездка, и ошибиться в направлении дорого.
    /// </remarks>
    public static string Explain(int theirMajor, int theirMinor, string theirProduct)
    {
        if (theirMajor == Major)
        {
            return string.Empty;
        }

        var direction = theirMajor < Major
            ? $"агент старее клиента — обновить агента до версии протокола {Major}"
            : $"агент новее клиента — обновить клиент до версии протокола {theirMajor}";

        return $"Версии протокола несовместимы: у нас {Major}.{Minor}, "
               + $"у собеседника {theirMajor}.{theirMinor} ({theirProduct}). {direction}.";
    }
}
