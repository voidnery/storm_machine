namespace StormMachine.App.ViewModels;

/// <summary>
/// Надпись об уровнях в шапке окна.
/// </summary>
/// <remarks>
/// Отдельно от оболочки, чтобы правило можно было проверить: до И-26 надпись была
/// константой «Уровень 0 — ядро» и не менялась ни от запуска с правами, ни от
/// заведённых учётных данных SNMP. Нашёл это оператор — надпись, которая не может
/// стать другой, ничего не сообщает, но выглядит как сообщение о состоянии.
/// <para>
/// <b>Уровни независимы.</b> Захват требует прав администратора, SNMP — учётных
/// данных оборудования, и одно без другого бывает сплошь и рядом. Поэтому
/// показывается не «верхний достигнутый», а те, что работают: «уровни 0 и 2» —
/// такое же законное состояние машины, как и «все три».
/// </para>
/// </remarks>
internal static class LevelBadge
{
    /// <summary>Что написано на самом чипе.</summary>
    public static string Describe(bool snmp, bool capture) => (snmp, capture) switch
    {
        (true, true) => "Все три уровня",
        (true, false) => "Уровни 0 и 1 — ядро и SNMP",
        (false, true) => "Уровни 0 и 2 — ядро и захват",
        _ => "Уровень 0 — ядро",
    };

    /// <summary>Что означают уровни и чего не хватает остальным.</summary>
    /// <remarks>
    /// Недоступное не прячется, а объясняется (UX-принцип 6): человек, прочитавший
    /// «уровень 0», должен узнать, что сделать для остальных, не уходя с этого экрана.
    /// </remarks>
    public static string Hint(bool snmp, bool capture)
    {
        var missing = new List<string>();

        if (!snmp)
        {
            missing.Add("для уровня 1 нужны учётные данные SNMP");
        }

        if (!capture)
        {
            missing.Add("для уровня 2 — права администратора");
        }

        return missing.Count == 0
            ? Scale + " Сейчас работают все три."
            : $"{Scale} Сейчас не хватает: {string.Join("; ", missing)}.";
    }

    /// <summary>
    /// Сама шкала.
    /// </summary>
    /// <remarks>
    /// Объяснялась только в разделе «Разработка», а он временный и уйдёт из релизной
    /// версии. После его удаления «Уровень 0» в шапке остался бы надписью без единого
    /// объяснения во всём продукте.
    /// </remarks>
    public const string Scale =
        "Уровень 0 — то, что работает у любого без прав администратора и без "
        + "дополнительных программ: измерения, инвентарь, карта, отчёты. "
        + "Уровень 1 добавляет опрос оборудования по SNMP — нужны учётные данные. "
        + "Уровень 2 добавляет захват кадров — нужны права администратора.";
}
