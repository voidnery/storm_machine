namespace StormMachine.Domain.Text;

/// <summary>
/// Согласование существительного с числом по-русски.
/// </summary>
/// <remarks>
/// Правило одно на весь продукт: 1 — «шаг», 2–4 — «шага», остальное — «шагов», а числа
/// от 11 до 14 идут в последнюю форму независимо от последней цифры. К И-19 это правило
/// было написано четыре раза — в расписании, в карте сети, в отчёте и в консоли, — и все
/// четыре раза одинаково. Четыре одинаковые копии одного правила означают, что рано или
/// поздно они станут тремя одинаковыми и одной другой.
/// <para>
/// Живёт в домене, потому что домен здесь и сам говорит с оператором по-русски:
/// <c>Schedule.Describe()</c> и карта сети складывают фразы, а не отдают их клиенту
/// по частям. Вынести правило выше домена значило бы оставить его недоступным тем,
/// кто им пользуется.
/// </para>
/// </remarks>
public static class Plural
{
    /// <summary>Выбирает форму слова по числу.</summary>
    /// <param name="count">Число, с которым согласуется слово.</param>
    /// <param name="one">Форма при 1: «шаг», «секунда», «узел».</param>
    /// <param name="few">Форма при 2–4: «шага», «секунды», «узла».</param>
    /// <param name="many">Форма в остальных случаях: «шагов», «секунд», «узлов».</param>
    public static string Of(int count, string one, string few, string many)
    {
        // Отрицательных чисел в предметной области нет, но брать модуль дешевле,
        // чем однажды получить «-2 шагов» из вычитания, ушедшего в минус.
        var value = Math.Abs(count);

        // Одиннадцать — не «одиннадцать шаг»: вторая десятка целиком идёт
        // в последнюю форму, и последняя цифра здесь ничего не решает.
        if (value % 100 is >= 11 and <= 14)
        {
            return many;
        }

        return (value % 10) switch
        {
            1 => one,
            2 or 3 or 4 => few,
            _ => many,
        };
    }

    /// <summary>Число вместе с согласованным словом: «3 шага».</summary>
    public static string With(int count, string one, string few, string many) =>
        $"{count.ToString(System.Globalization.CultureInfo.InvariantCulture)} {Of(count, one, few, many)}";
}
