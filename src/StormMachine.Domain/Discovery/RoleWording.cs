namespace StormMachine.Domain.Discovery;

/// <summary>
/// Как назвать категорию устройства там, где рядом нет ни цвета, ни места на фразу.
/// </summary>
/// <remarks>
/// До И-24+ догадку классификатора отличал вопросительный знак: «сервер?» против
/// «сервер». Знак читался как опечатка или как вопрос продукта к оператору, и его
/// убрали. Само различие осталось: категория, выведенная по портам, вендору и имени,
/// — это догадка, и выдавать её за наблюдение нельзя.
///
/// Где есть цвет (карта) — догадку показывает бледная рамка; где есть место на фразу
/// (панель узла) — фраза целиком. Остаётся третий случай: строка таблицы в консоли,
/// где нет ни того, ни другого. Там оговорку несёт само слово, и это слово одно
/// на весь продукт — иначе консоль и окно разойдутся, оставаясь каждый по-своему
/// «правильными».
/// </remarks>
public static class RoleWording
{
    /// <summary>
    /// Тег категории для строки без цвета: догадка так и называется догадкой.
    /// </summary>
    public static string? Tag(string? role, bool guessed) => role switch
    {
        null or "" => null,
        _ => guessed ? $"похоже на {role}" : role,
    };
}
