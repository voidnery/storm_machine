namespace StormMachine.Domain.Results;

/// <summary>
/// Как продукт называет вердикт.
/// </summary>
/// <remarks>
/// Словарей здесь два, и они <b>намеренно</b> не сведены в один: «в норме» говорят
/// о законченном измерении, «норма» — о состоянии монитора прямо сейчас. Это разные
/// вопросы, и отвечать на них одним словом было бы неточно.
/// <para>
/// Сведено другое — копии. К И-19 значок был написан три раза (два экрана и консоль),
/// слово прогона — два, слово монитора — три; все копии совпадали дословно. Пока
/// клиентов два, расхождение стоит недорого: консоль и окно просто скажут об одном
/// измерении разными словами, и оператор решит, что видит разные вещи. Появится третий
/// клиент — сетевая панель server-варианта — и цена вырастет.
/// </para>
/// </remarks>
public static class VerdictWording
{
    /// <summary>Значок вердикта для строки списка.</summary>
    public static string Mark(VerdictLevel level) => level switch
    {
        VerdictLevel.Pass => "✓",
        VerdictLevel.Warn => "!",
        VerdictLevel.Fail => "✗",
        _ => "·",
    };

    /// <summary>
    /// Как называется исход прогона: «в норме», «не прошло».
    /// </summary>
    /// <remarks>
    /// Прошедшее время не случайно: измерение закончилось, и речь о том, чем оно
    /// кончилось.
    /// </remarks>
    public static string Outcome(VerdictLevel level) => level switch
    {
        VerdictLevel.Pass => "в норме",
        VerdictLevel.Warn => "предупреждение",
        VerdictLevel.Fail => "не прошло",
        _ => "не оценено",
    };

    /// <summary>
    /// Как называется состояние монитора: «норма», «отказ».
    /// </summary>
    /// <remarks>
    /// Настоящее время и назывной падеж: монитор не «не прошёл» когда-то, а находится
    /// в состоянии прямо сейчас. Что означает <see cref="VerdictLevel.Unknown"/>,
    /// решает вызывающий: «ещё не проверялся» для монитора, который ни разу не работал,
    /// и «неизвестно» для отдельной проверки без порогов — разница для оператора
    /// существенная, и подставлять за него общее слово неправильно.
    /// </remarks>
    public static string State(VerdictLevel level, string unknown = "неизвестно") => level switch
    {
        VerdictLevel.Pass => "норма",
        VerdictLevel.Warn => "предупреждение",
        VerdictLevel.Fail => "отказ",
        _ => unknown,
    };
}
