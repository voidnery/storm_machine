namespace StormMachine.Domain.Results;

/// <summary>
/// Форма результата пробы.
/// </summary>
/// <remarks>
/// Появилась в И-2. Шесть проб дали четыре формы данных, и угадывать форму по содержимому
/// сэмплов — значит строить показ и хранение на догадках. Проба объявляет форму сама,
/// как объявляет параметры.
/// <para>
/// Живёт в домене, а не в слое приложения: от формы зависит раскладка результата на ряды
/// (<see cref="SeriesBreakdown"/>) — это правило модели, а не деталь интерфейса.
/// В И-3 выяснилось это буквально: попытка оставить перечисление в слое приложения
/// заставила бы домен ссылаться наружу.
/// </para>
/// </remarks>
public enum ProbeResultShape
{
    /// <summary>Один ряд чисел во времени: ICMP, TCP-connect, UDP.</summary>
    ScalarSeries,

    /// <summary>Одно событие, разложенное на фазы: HTTP-водопад, рукопожатие TLS.</summary>
    PhasedTiming,

    /// <summary>Несколько независимых рядов для сравнения между собой: резолверы DNS.</summary>
    ComparedSeries,

    /// <summary>Матрица «хоп × попытка»: traceroute.</summary>
    PathTrace,
}
