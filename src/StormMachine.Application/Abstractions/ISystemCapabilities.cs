namespace StormMachine.Application.Abstractions;

/// <summary>
/// Что позволяет сама машина.
/// </summary>
/// <remarks>
/// Отдельно от <see cref="INetworkEnvironment"/>: тот описывает сеть, этот — систему
/// под ногами. Права процесса и возможность открыть сырой сокет — вещи, от которых
/// зависит, что продукт вообще может, и узнавать их он обязан у системы,
/// а не предполагать.
/// <para>
/// Про драйвер захвата здесь ничего нет, и это решение И-25. Раньше было: два
/// свойства искали на диске библиотеку Npcap. Их никто не читал — на вопрос
/// «можно ли слушать» отвечает сам источник захвата, у которого ответов четыре,
/// а не два, и который знает про встроенный в Windows pktmon. Порт, отвечающий
/// мимо, хуже отсутствующего: однажды по нему решат.
/// </para>
/// </remarks>
public interface ISystemCapabilities
{
    /// <summary>Работает ли процесс с правами администратора.</summary>
    bool IsElevated { get; }

    /// <summary>
    /// Можно ли открыть сырой сокет.
    /// </summary>
    /// <remarks>
    /// Проверяется попыткой, а не выводом из прав: на части систем сырые сокеты
    /// доступны и без администратора, а на части закрыты политикой даже с ним.
    /// Гадать по одному флагу прав значило бы соврать в обе стороны.
    /// </remarks>
    bool CanOpenRawSockets { get; }
}
