namespace StormMachine.Application.Abstractions;

/// <summary>
/// Что позволяет сама машина.
/// </summary>
/// <remarks>
/// Отдельно от <see cref="INetworkEnvironment"/>: тот описывает сеть, этот — систему
/// под ногами. Права процесса, установленный драйвер захвата, возможность открыть
/// сырой сокет — вещи, от которых зависит, что продукт вообще может, и узнавать их
/// он обязан у системы, а не предполагать.
/// </remarks>
public interface ISystemCapabilities
{
    /// <summary>Работает ли процесс с правами администратора.</summary>
    bool IsElevated { get; }

    /// <summary>
    /// Установлен ли Npcap.
    /// </summary>
    /// <remarks>
    /// Продукт его <b>не распространяет</b> ни при каких условиях: лицензия NPSL
    /// основана на GPLv2, но open-source не является и распространение без отдельного
    /// разрешения запрещает. У Wireshark для этого есть именное исключение, у нас
    /// его нет (решение R-02 исследования). Продукт умеет только обнаружить уже
    /// установленный.
    /// </remarks>
    bool IsCaptureDriverInstalled { get; }

    /// <summary>Что именно найдено — версия драйвера, если её удалось прочитать.</summary>
    string? CaptureDriverDescription { get; }

    /// <summary>
    /// Можно ли открыть сырой сокет.
    /// </summary>
    /// <remarks>
    /// Проверяется попыткой, а не выводом из прав: на части систем сырые сокеты
    /// доступны и без администратора, а на части закрыты политикой даже с ним.
    /// Гадать по одному флагу прав значило бы соврать в обе стороны.
    /// </remarks>
    bool CanOpenRawSockets { get; }
}
