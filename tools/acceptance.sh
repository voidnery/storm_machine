#!/bin/sh
# Прогон приёмки итерации: собирает продукт, поднимает стенд, выполняет шаги подряд
# и складывает всё в один файл, который можно отдать целиком.
#
# Появился в И-17 по прямой просьбе оператора: набирать полтора десятка команд руками
# каждую итерацию долго, а главное — легко пропустить шаг и не заметить этого.
#
# Три свойства, ради которых он написан именно так:
#
#   1. НЕ ТРОГАЕТ РАБОЧУЮ БАЗУ. Всё идёт в свой файл во временном каталоге через
#      STORM_DB. Проверки не должны подмешиваться в историю измерений оператора —
#      однажды это уже случилось (см. docs/STATUS.md, урок И-13).
#
#   2. НЕ СКРЫВАЕТ ОТКАЗОВ. Шаг, вернувший ненулевой код, помечается и попадает
#      в итог. Скрипт, который «прошёл» при упавшем шаге, хуже отсутствия скрипта.
#
#   3. ОСТАВЛЯЕТ СЛЕД. Весь вывод пишется в artifacts/acceptance-*.txt — этот файл
#      и есть то, что оператор присылает вместо копирования из консоли по кускам.
#
# Запуск:
#   sh tools/acceptance.sh              — последняя итерация
#   sh tools/acceptance.sh И-16         — другая итерация
#   sh tools/acceptance.sh --список     — что вообще можно прогнать
#   sh tools/acceptance.sh --без-сборки — пропустить публикацию, если она свежая
#   sh tools/acceptance.sh --оставить   — не удалять временную базу и стенд
set -u

root="$(cd "$(dirname "$0")/.." && pwd)"
cli="$root/src/StormMachine.Cli/bin/Release/net10.0-windows/win-x64/publish/storm.exe"
spike="$root/spikes/spike-08-snmp/bin/Release/net10.0-windows/win-x64/spike08.exe"

iteration=""
build=1
keep=0

for arg in "$@"; do
    case "$arg" in
        --список|--list)
            echo "Доступные прогоны:"
            echo "  И-19  рефакторинг и баг-чекинг — проверки, нагрузка, честность показа"
            echo "  И-18  уровень 2: захват — честная деградация без Npcap, разбор кадров"
            echo "  И-17  уровень 1: SNMP — опрос оборудования, порты, соседи, карта"
            echo "  И-16  полировка MVP — возможности, профили, мониторы формой"
            echo "  всё   все подряд"
            exit 0
            ;;
        --без-сборки|--no-build) build=0 ;;
        --оставить|--keep) keep=1 ;;
        -*)
            echo "Неизвестный ключ: $arg. Список ключей — в заголовке tools/acceptance.sh" >&2
            exit 2
            ;;
        *) iteration="$arg" ;;
    esac
done

[ -z "$iteration" ] && iteration="И-19"

# --------------------------------------------------------------------- обстановка

work="${TMPDIR:-/tmp}/storm-acceptance-$$"
mkdir -p "$work"

# Своя база и своё окружение: рабочая история оператора остаётся нетронутой.
STORM_DB="$work/acceptance.db"
export STORM_DB

mkdir -p "$root/artifacts"
stamp="$(date +%Y%m%d-%H%M%S)"
log="$root/artifacts/acceptance-$(echo "$iteration" | tr -d ' ')-$stamp.txt"

passed=0
failed=0
failed_names=""
simulator=""

say() { printf '%s\n' "$*" | tee -a "$log"; }

rule() { say "────────────────────────────────────────────────────────────────────────"; }

# Команда печатается так, как её набрал бы человек. Полный путь до папки публикации
# в протоколе только мешает читать, а воспроизвести шаг по нему всё равно нельзя:
# у оператора продукт стоит в другом месте.
shorten() { printf '%s' "$*" | sed -e "s|$cli|storm|g" -e "s|$spike|spike08|g"; }

# Один шаг приёмки: заголовок, сама команда, её вывод на экран и в протокол,
# отметка об исходе.
#
# Команда печатается перед выполнением намеренно. Оператор должен видеть не только
# что получилось, но и чем это получено: шаг, вывод которого нельзя воспроизвести
# руками, ничего не подтверждает.
show() {
    expected=0
    step "$@"
}

# Шаг, у которого ОЖИДАЕТСЯ отказ.
#
# Нужен там, где правильное поведение продукта — отказаться: команда захвата
# без установленного драйвера обязана вернуть ненулевой код. Считать это провалом
# приёмки неверно, но и не проверять нельзя: если такая команда однажды начнёт
# молча возвращать ноль, отказ превратится в тихую ложь, и заметить это будет негде.
# Поэтому ожидаемый код проверяется так же строго, как нулевой.
refuses() {
    expected=1
    step "$@"
}

step() {
    title="$1"
    shift

    rule
    say "  $title"
    say "  \$ $(shorten "$@")"
    rule

    # Код возврата снимается ВНУТРИ конвейера, а не после него.
    #
    # Иначе $? принадлежал бы tee, а tee успешен почти всегда — и упавший шаг
    # попал бы в итог пройденным. Скрипт приёмки, который врёт про исход шага,
    # хуже отсутствия скрипта: он превращает проверку в её видимость.
    # В POSIX sh нет PIPESTATUS, поэтому код кладётся в файл.
    { "$@" 2>&1; echo $? >"$work/code"; } | tee -a "$log"

    code="$(cat "$work/code" 2>/dev/null || echo 1)"

    if [ "$code" -eq "$expected" ]; then
        passed=$((passed + 1))
        say "$([ "$expected" -eq 0 ] && echo "  ✓ шаг пройден" || echo "  ✓ отказ получен, как и ожидалось")"
    else
        failed=$((failed + 1))
        failed_names="$failed_names
  ✗ $title (код $code, ожидался $expected)"
        say "  ✗ ШАГ НЕ ПРОШЁЛ: код возврата $code, ожидался $expected"
    fi

    say ""
}

cleanup() {
    if [ -n "$simulator" ] && kill -0 "$simulator" 2>/dev/null; then
        kill "$simulator" 2>/dev/null
        say "Стенд остановлен."
    fi

    if [ $keep -eq 0 ]; then
        rm -rf "$work"
    else
        say "Временная база оставлена: $work"
    fi
}

trap cleanup EXIT INT TERM

# ----------------------------------------------------------------------- сборка

publish() {
    [ $build -eq 0 ] && return 0

    say "Публикую консоль (обрезка включена — проверяется то, что уедет пользователю)…"

    if ! dotnet publish "$root/src/StormMachine.Cli" -c Release --nologo -v quiet >>"$log" 2>&1; then
        say "Публикация консоли не удалась. Подробности в $log"
        exit 1
    fi

    say "Собираю стенд…"

    if ! dotnet build "$root/spikes/spike-08-snmp/Spike08.csproj" -c Release --nologo -v quiet >>"$log" 2>&1; then
        say "Сборка стенда не удалась. Подробности в $log"
        exit 1
    fi
}

# Проверка снаряжения перед прогоном.
#
# Появилась после приёмки И-17, где неполная публикация дала девять одинаковых
# трасс подряд вместо одного внятного сообщения. Отказ продукта и отказ сборки —
# разные вещи, и путать их в протоколе приёмки нельзя: первое требует правки кода,
# второе — пересборки.
#
# Публикация вдобавок умеет быть «свежей» при испорченном выводе: incremental
# publish сверяет входы, а не результат, и уже собранного не восстанавливает.
# Поэтому при отказе папка публикации сносится и собирается заново — один раз.
ready() {
    if "$cli" about >/dev/null 2>&1; then
        return 0
    fi

    say "Опубликованная консоль не запускается. Пересобираю с нуля…"
    say ""

    rm -rf "$root/src/StormMachine.Cli/bin/Release/net10.0-windows/win-x64/publish"

    if ! dotnet publish "$root/src/StormMachine.Cli" -c Release --nologo -v quiet >>"$log" 2>&1; then
        say "Публикация не удалась. Подробности в $log"
        exit 1
    fi

    if "$cli" about >/dev/null 2>&1; then
        say "Пересборка помогла — продолжаю."
        say ""

        return 0
    fi

    say "Консоль не запускается и после пересборки. Это отказ продукта, а не прогона:"
    say ""

    "$cli" about 2>&1 | head -20 | tee -a "$log"

    exit 1
}

# --------------------------------------------------------------------- сценарии

# Стенд вместо железа: управляемого коммутатора под рукой может не быть, а проверять
# чтение таблиц на чём-то надо. Отвечает теми же байтами, что оборудование.
start_simulator() {
    if [ ! -x "$spike" ]; then
        say "Стенд не собран: $spike"
        exit 1
    fi

    "$spike" serve 16100 >>"$log" 2>&1 &
    simulator=$!

    sleep 2

    if ! kill -0 "$simulator" 2>/dev/null; then
        say "Стенд не поднялся. Возможно, порт 16100 занят."
        exit 1
    fi

    say "Стенд поднят: коммутатор-дублёр на 127.0.0.1:16100, сообщество public."
    say ""
}

scenario_i17() {
    say "ПРИЁМКА И-17 — уровень 1: SNMP"
    say ""
    say "Что проверяется: опрос оборудования, разбор таблиц, счётчики с их отказами"
    say "и главное — карта, на которой устройство висит на порту коммутатора,"
    say "а не «где-то в этом широковещательном домене»."
    say ""

    start_simulator

    show "1. Набор учётных данных заводится, и продукт сразу говорит, чего он не защищает" \
        "$cli" snmp creds add "стенд" --версия v2c --community public --порт 16100

    show "2. Устройство опознано: модель, имя, где стоит, сколько работает" \
        "$cli" snmp probe 127.0.0.1

    show "3. Порты: три состояния различаются, ошибки показаны долей, а не штуками" \
        "$cli" snmp interfaces 127.0.0.1 --нагрузка 10

    show "4. Соседи по LLDP — с оговоркой про неуправляемый коммутатор между ними" \
        "$cli" snmp neighbors 127.0.0.1

    show "5. Таблица пересылки: какой адрес в каком порту" \
        "$cli" snmp fdb 127.0.0.1

    show "6. Поиск конкретного адреса по портам" \
        "$cli" snmp fdb 127.0.0.1 --mac A4-BB-6D-11-22-33

    show "7. Карта: коммутатор и его сосед появились подтверждёнными связями" \
        "$cli" topology --snmp --устройство 127.0.0.1 --no-paths

    show "8. Обход произвольной ветки — для случаев, которых продукт не предусмотрел" \
        "$cli" snmp walk 127.0.0.1 1.3.6.1.2.1.1 --предел 10

    show "9. Список наборов: пароли и строки сообщества заменены пометкой" \
        "$cli" snmp creds

    say "Что смотреть глазами:"
    say "  · шаг 3 — Gi0/2 сыплет ошибками (порядка 300 на миллион), Gi0/3 включён"
    say "    без линка, Gi0/4 выключен администратором. Три разных случая."
    say "  · шаг 3 — подписи портов по-русски: «серверная, стойка 2». Если там"
    say "    вопросительные знаки — сломана кодировка."
    say "  · шаг 7 — sw-spike-01 и его сосед sw-core-01 связаны подтверждённо."
    say "  · шаг 9 — самой строки сообщества в списке нет ни в каком виде."
    say "    Список смотрят не затем, чтобы узнать пароль."
    say ""
}

scenario_i16() {
    say "ПРИЁМКА И-16 — полировка MVP"
    say ""

    show "1. Что продукт может на этой машине: уровни и причины недоступного" \
        "$cli" capabilities --подробно

    show "2. Профиль по приметам текущей сети" \
        "$cli" profiles add "приёмка" --отсюда

    show "3. Узнавание сети: догадка, а не переключение" \
        "$cli" profiles detect

    show "4. Переключение — решение человека" \
        "$cli" profiles use "приёмка"

    show "5. Измерение под активным профилем" \
        "$cli" ping 127.0.0.1 --count 4 -q --save

    # Профиль виден не в выводе измерения, а в условиях сохранённого прогона —
    # там, где он и нужен: через полгода читать будут журнал, а не консоль.
    run_id="$(grep -o 'Сохранено в журнал: [0-9a-fA-F-]\{36\}' "$log" | tail -1 | awk '{print $4}')"

    if [ -n "$run_id" ]; then
        show "6. Профиль записан в условия измерения, а не только в настройки" \
            "$cli" runs show "$run_id"
    else
        say "  ! Не удалось выяснить идентификатор прогона — шаг 6 пропущен."
        say ""
    fi

    say "Что смотреть глазами:"
    say "  · шаг 1 — недоступное объяснено, а не спрятано: у каждой строки есть причина."
    say "  · шаг 6 — среди условий прогона строка «Профиль : приёмка»."
    say "    Без неё замер у заказчика и замер в офисе через полгода не различить."
    say ""
}

scenario_i18() {
    say "ПРИЁМКА И-18 — уровень 2: захват пакетов"
    say ""
    say "Условие приёмки прямое: без Npcap продукт работает полностью и честно"
    say "сообщает, чего не хватает; с Npcap функции появляются. На этой машине"
    say "драйвера нет — значит проверяется первая половина, и она главная:"
    say "именно так продукт увидит большинство пользователей."
    say ""

    show "1. Захват сам объясняет, чего не хватает и откуда это взять" \
        "$cli" capture

    show "2. Уровень 2 показан в возможностях, а не спрятан" \
        "$cli" capabilities --подробно

    refuses "3. Список адаптеров отказывает внятно, а не падает" \
        "$cli" capture devices

    refuses "4. Прослушивание отказывает так же внятно" \
        "$cli" capture listen --секунд 5

    show "5. Карта строится и без захвата — уровень 2 необязателен" \
        "$cli" topology --захват 5 --no-paths

    # Разбор кадров проверить командой нельзя: без драйвера слушать нечего.
    # Он покрыт проверками на записанных байтах — их и прогоняем, честно называя,
    # что это проверки, а не работа продукта.
    show "6. Разбор кадров: LLDP, CDP и DHCP на записанных байтах" \
        dotnet test "$root/tests/StormMachine.Capture.UnitTests" -c Debug --nologo -v quiet

    say "Что смотреть глазами:"
    say "  · шаг 1 — сказано, что Npcap не входит в поставку ни при каких условиях,"
    say "    и дана ссылка. Продукт не предлагает поставить его за вас."
    say "  · шаг 2 — уровень 2 показан с причиной, а не спрятан. Уровень 1 при этом"
    say "    больше не числится «запланированным»: он сделан в И-17."
    say "  · шаги 3 и 4 — отказ ожидаемый: без драйвера команда обязана вернуть"
    say "    ненулевой код. Молчаливый ноль здесь был бы тихой ложью."
    say "  · шаг 5 — карта построена, отсутствие захвата названо строкой сверху."
    say ""
    say "Если поставите Npcap с npcap.com, те же шаги 3–5 покажут адаптеры,"
    say "услышанных соседей и свой порт на коммутаторе. Ставить его или нет —"
    say "решение ваше: продукт этого не делает и делать не будет."
    say ""
}

scenario_i19() {
    say "ПРИЁМКА И-19 — масштабный рефакторинг и баг-чекинг"
    say ""
    say "У этой итерации нет новых возможностей, и приёмка у неё другая по сути."
    say "Проверяется не «появилось ли», а «не сломалось ли и стало ли честнее»:"
    say "четыре исправленных дефекта, сведённые копии формулировок, покрытие тех"
    say "трёх проектов, где не было ни одного теста, и числа нагрузочного прогона."
    say ""

    show "1. Все проверки, кроме нагрузочных"         dotnet test "$root" -c Debug --nologo -v quiet --filter "Категория!=Нагрузка"

    show "2. Нагрузка: карта на 4096 узлов и год работы монитора в журнале"         dotnet test "$root/tests/StormMachine.LoadTests" -c Release --nologo -v quiet

    show "3. Условия измерения в шапке — те же, что уйдут в журнал"         "$cli" ping 127.0.0.1 --count 4 --save

    show "4. Журнал: размер базы и что в ней лежит"         "$cli" runs usage

    show "5. Возможности: ни одна строка не обещает того, что уже сделано"         "$cli" capabilities --подробно

    say "Что смотреть глазами:"
    say "  · шаг 1 — 918 проверок. Было 803: прибавка это покрытие консоли,"
    say "    каналов оповещения и проб агента, у которых тестов не было вовсе."
    say "  · шаг 2 — числа в artifacts/load-*.txt. Их ценность не в том, что прогон"
    say "    прошёл, а в том, с чем сравнить следующий: карта на 4096 узлов за 24 мс,"
    say "    год работы монитора это 153 МБ и 105 120 прогонов, журнал открывается"
    say "    за 4 мс, уборка миллиона сэмплов за 2.4 с."
    say "  · шаг 3 — в шапке названы интерфейс, методика со ссылкой на стандарт"
    say "    и порог разрешения. Раньше шапка не показывала активный профиль,"
    say "    а в журнал он писался: читалось одно, хранилось другое."
    say "  · шаг 4 — на свежей базе приёмки строки про свободное место нет,"
    say "    и это правильно: показывать нечего. Она появляется, когда уборке"
    say "    есть что освободить, — а до И-19 её не было вовсе, и оператор,"
    say "    убравший миллион сэмплов, видел прежний размер файла и делал"
    say "    единственный возможный вывод: уборка не сработала. Вывод неверен,"
    say "    место освобождено внутри файла. Случай виден в шаге 2."
    say "  · шаг 5 — «появится в итерации N» не стоит рядом с тем, что уже работает."
    say "    Дважды ловили обратное; теперь это удерживается проверкой."
    say ""
}

# ------------------------------------------------------------------------- ход

: >"$log"

say "Storm Machine — прогон приёмки"
say "Итерация : $iteration"
say "Начало   : $(date '+%Y-%m-%d %H:%M:%S')"
say "База     : $STORM_DB  (рабочая история не затрагивается)"
say "Протокол : $log"
say ""

publish

if [ ! -x "$cli" ]; then
    say "Не найдена опубликованная консоль: $cli"
    say "Запустите без ключа --без-сборки."
    exit 1
fi

ready

case "$iteration" in
    И-19|и-19|i19|19) scenario_i19 ;;
    И-18|и-18|i18|18) scenario_i18 ;;
    И-17|и-17|i17|17) scenario_i17 ;;
    И-16|и-16|i16|16) scenario_i16 ;;
    всё|все|all) scenario_i16; scenario_i17; scenario_i18; scenario_i19 ;;
    *)
        say "Не знаю такого прогона: $iteration"
        say "Список: sh tools/acceptance.sh --список"
        exit 2
        ;;
esac

rule
say "  ИТОГ"
rule
say "  Шагов пройдено : $passed"
say "  Не прошло      : $failed"

if [ $failed -gt 0 ]; then
    say "$failed_names"
fi

say ""
say "  Протокол целиком: $log"
say "  Его и присылайте — там и команды, и вывод, и коды возврата."
say ""

if [ $failed -gt 0 ]; then
    say "  Часть шагов не прошла. Это результат прогона, а не поломка скрипта:"
    say "  смотрите вывод упавшего шага в протоколе."
